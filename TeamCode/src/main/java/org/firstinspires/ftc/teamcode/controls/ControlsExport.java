package org.firstinspires.ftc.teamcode.controls;

import org.firstinspires.ftc.teamcode.opmodes.ArcLight;
import org.firstinspires.ftc.teamcode.opmodes.BasicDriveTeleOp;
import org.firstinspires.ftc.teamcode.opmodes.CycleReadout;
import org.firstinspires.ftc.teamcode.opmodes.TeleOpConfig;
import org.firstinspires.ftc.teamcode.subsystems.DriveSubsystem;
import org.firstinspires.ftc.teamcode.subsystems.IndicatorSubsystem;
import org.firstinspires.ftc.teamcode.subsystems.LauncherSubsystem;
import org.firstinspires.ftc.teamcode.subsystems.TurretSubsystem;

import java.util.Locale;
import java.util.Map;

/**
 * The controls as data: {@link ControlScheme}'s match layout, both with the turret aiming and
 * locked forward, and the TeleOp switches that decide what a button does. {@code CheatSheetTest}
 * writes it to {@code TeamCode/cheat-sheets/controls.json}, beside the printed sheet it is made
 * from the same layout as, and fails while the committed copy is stale. The Visualizer's driver
 * drill reads that file, so the drill's buttons are the robot's and never typed in by hand.
 *
 * <p>Also the driver's Square ({@link LaunchSpotsExport}): the launch spots, where the button drives
 * for each alliance, and the pick from a grid of poses, so the drill drives where the robot does.
 *
 * <p>Shared values only: a robot's {@code RobotDifferences} lines are not applied here (they can be
 * applied once per app run), so a drill that needs a per-robot value says so where it uses it.
 */
public final class ControlsExport {

    private ControlsExport() {
    }

    /** The file, as JSON text with a newline at the end. */
    public static String json() {
        StringBuilder out = new StringBuilder();
        out.append("{\n");
        field(out, 1, "about", "Generated by CheatSheetTest from TeamCode controls/ControlScheme"
                + " (ControlsExport); do not edit. The match TeleOp's layout: gamepad 1 is the driver,"
                + " gamepad 2 the operator.").append(",\n");
        field(out, 1, "flowerPickDefault", ControlScheme.DEFAULT_FLOWER_PICK.name()).append(",\n");
        indent(out, 1).append("\"triggerPressed\": ").append(num(Input.TRIGGER_PRESSED)).append(",\n");
        indent(out, 1).append("\"inputs\": [\n");
        Input[] inputs = Input.values();
        for (int i = 0; i < inputs.length; i++) {
            indent(out, 2).append("{\"input\": ").append(quote(inputs[i].name()))
                    .append(", \"label\": ").append(quote(inputs[i].label))
                    .append(", \"stick\": ").append(inputs[i].isStick()).append('}')
                    .append(i + 1 < inputs.length ? ",\n" : "\n");
        }
        indent(out, 1).append("],\n");
        indent(out, 1).append("\"layouts\": {\n");
        layout(out, "turretAiming", false);
        out.append(",\n");
        layout(out, "turretLocked", true);
        out.append('\n');
        indent(out, 1).append("},\n");
        indent(out, 1).append("\"teleOp\": {\n");
        String[][] switches = {
                {"normalSpeed", num(TeleOpConfig.normalSpeed)},
                {"slowSpeed", num(TeleOpConfig.slowSpeed)},
                {"intakeAlwaysOn", String.valueOf(TeleOpConfig.intakeAlwaysOn)},
                {"idleAtPlay", String.valueOf(TeleOpConfig.idleAtPlay)},
                {"launchSpot", String.valueOf(TeleOpConfig.launchSpot)},
                {"goToSpotAlsoFires", String.valueOf(TeleOpConfig.goToSpotAlsoFires)},
                {"startTurretAiming", String.valueOf(TeleOpConfig.startTurretAiming)},
                {"circleTurnsIntoArc", String.valueOf(TeleOpConfig.circleTurnsIntoArc)},
                {"arcTurnMarginDeg", num(TeleOpConfig.arcTurnMarginDeg)},
                {"enforceFiringArc", String.valueOf(TeleOpConfig.enforceFiringArc)},
                {"enforceAtSpeedGate", String.valueOf(TeleOpConfig.enforceAtSpeedGate)},
                {"enforceAimGate", String.valueOf(TeleOpConfig.enforceAimGate)},
                {"aimToleranceDeg", num(TeleOpConfig.aimToleranceDeg)},
                {"chassisAimKp", num(TeleOpConfig.chassisAimKp)},
                {"chassisAimMinTurn", num(TeleOpConfig.chassisAimMinTurn)},
                {"chassisAimMaxTurn", num(TeleOpConfig.chassisAimMaxTurn)},
                {"headingLockConeDeg", num(TeleOpConfig.headingLockConeDeg)},
                {"headingLockStepDeg", num(TeleOpConfig.headingLockStepDeg)},
                {"headingLockKp", num(TeleOpConfig.headingLockKp)},
                {"headingLockKd", num(TeleOpConfig.headingLockKd)},
                {"headingLockMinTurn", num(TeleOpConfig.headingLockMinTurn)},
                {"headingLockMaxTurn", num(TeleOpConfig.headingLockMaxTurn)},
                {"headingLockStopDeg", num(TeleOpConfig.headingLockStopDeg)},
                {"turretModeHoldMs", num(BasicDriveTeleOp.RESET_HOLD_MS)},
                {"driveAccelPerSec", num(DriveSubsystem.accelPerSec)},
                {"turnAccelPerSec", num(DriveSubsystem.turnAccelPerSec)},
                {"turretLockedForwardShared", String.valueOf(TurretSubsystem.lockedForward)},
                {"turretArcLeftDeg", num(TurretSubsystem.arcLeftDeg)},
                {"turretArcRightDeg", num(TurretSubsystem.arcRightDeg)},
                {"turretTopSpeedDps", num(TurretSubsystem.topSpeedDps)},
                {"trimStepDeg", num(TeleOpConfig.trimStepDeg)},
                {"trimFineStepDeg", num(TeleOpConfig.trimFineStepDeg)},
                {"maxAimTrimDeg", num(TeleOpConfig.maxAimTrimDeg)},
                {"launcherTargetTps", num(LauncherSubsystem.targetTicksPerSecond)},
                {"launcherTrimStepTps", num(TeleOpConfig.launcherTrimStepTps)},
                {"launcherTrimFineStepTps", num(TeleOpConfig.launcherTrimFineStepTps)},
                {"maxLauncherTrimTps", num(TeleOpConfig.maxLauncherTrimTps)},
                {"launcherKeepSpinningAfterSquareS", num(TeleOpConfig.launcherKeepSpinningAfterSquareS)},
                {"staleStickCancelsAfterS", num(TeleOpConfig.staleStickCancelsAfterS)},
        };
        for (int i = 0; i < switches.length; i++) {
            indent(out, 2).append(quote(switches[i][0])).append(": ").append(switches[i][1])
                    .append(i + 1 < switches.length ? ",\n" : "\n");
        }
        indent(out, 1).append("},\n");
        out.append(LaunchSpotsExport.json(1)).append(",\n");
        // The indicator light's numbers (IndicatorSubsystem, ArcLight), so the drill's light flashes and
        // pulses as the robot's does.
        indent(out, 1).append("\"indicator\": {\"flashMs\": ").append(num(IndicatorSubsystem.FLASH_MS))
                .append(", \"arcTurnPulseMs\": ").append(num(IndicatorSubsystem.ARC_TURN_PULSE_MS))
                .append(", \"arcLightClearMs\": ").append(ArcLight.CLEAR_MS).append("},\n");
        indent(out, 1).append("\"practiceReadout\": {\"budgetS\": ").append(num(CycleReadout.BUDGET_S))
                .append(", \"budgetPieces\": ").append(CycleReadout.BUDGET_PIECES)
                .append(", \"mergeS\": ").append(num(CycleReadout.MERGE_S))
                .append(", \"split\": [\"drive to pieces\", \"pick up\", \"drive loaded\", \"spin-up and aim\", \"feed\"]}\n");
        out.append("}\n");
        return out.toString();
    }

    private static void layout(StringBuilder out, String name, boolean turretLocked) {
        Map<Action, Input> map = ControlScheme.layout(ControlScheme.DEFAULT_FLOWER_PICK, turretLocked,
                TeleOpConfig.launchSpot);
        indent(out, 2).append(quote(name)).append(": [\n");
        int i = 0;
        for (Map.Entry<Action, Input> entry : map.entrySet()) {
            Action action = entry.getKey();
            indent(out, 3).append("{\"pad\": ").append(quote(action.pad.name()))
                    .append(", \"action\": ").append(quote(action.name()))
                    .append(", \"input\": ").append(quote(entry.getValue().name()))
                    .append(", \"description\": ").append(quote(action.description)).append('}')
                    .append(++i < map.size() ? ",\n" : "\n");
        }
        indent(out, 2).append(']');
    }

    private static StringBuilder field(StringBuilder out, int depth, String key, String value) {
        return indent(out, depth).append(quote(key)).append(": ").append(quote(value));
    }

    private static StringBuilder indent(StringBuilder out, int depth) {
        for (int i = 0; i < depth; i++) out.append("  ");
        return out;
    }

    private static String num(double v) {
        return v == Math.rint(v) && Math.abs(v) < 1e9 ? String.format(Locale.ROOT, "%.1f", v) : String.valueOf(v);
    }

    /** {@code s} as a JSON string. */
    public static String quote(String s) {
        StringBuilder b = new StringBuilder("\"");
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == '"' || c == '\\') b.append('\\').append(c);
            else if (c == '\n') b.append("\\n");
            else if (c < 0x20 || c > 0x7e) b.append(String.format(Locale.ROOT, "\\u%04x", (int) c));
            else b.append(c);
        }
        return b.append('"').toString();
    }
}
