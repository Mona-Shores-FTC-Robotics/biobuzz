/**
 * Runs an Autonomous generated by the Auto Builder. Each generated Auto gets a five-line OpMode:
 *
 * <pre>
 * &#64;Autonomous(name = "Hive Rush " + HiveRushAuto.SAVED, group = "Auto")
 * public class HiveRushOpMode extends BuiltAuto {
 *     public HiveRushOpMode() {
 *         super(HiveRushAuto.SOURCE, HiveRushAuto.COMMANDS, HiveRushAuto.TRIGGERS,
 *                 HiveRushAuto.DRAWN_FOR, HiveRushAuto::startPose, HiveRushAuto::build,
 *                 HiveRushAuto.OPTIONS);
 *     }
 * }
 * </pre>
 *
 * <p>The name ends with {@code SAVED}, when the Auto's .pp was saved ({@code 10-31|12:22AM}, Michigan
 * time), so after a Sloth Load the Driver Station shows which save is on the robot. It is empty for a
 * .pp with no save time, until the Auto is next saved.
 *
 * <p>At INIT it checks every name the Auto uses against {@link AutoRegistration} and builds the
 * path follower, so a missing mechanism or an untuned robot stops it there, with the reason. At
 * PLAY it turns the Auto half a turn about the field centre if the alliance is not the one it was
 * drawn for (BIOBUZZ is rotationally symmetric, not mirrored), sets the start pose and
 * starts. It never guesses an alliance: with none chosen it does not move.
 *
 * <p>It declares its start ({@link #startPosition()}) so the start check runs during INIT and the
 * camera can confirm the alliance without a button press. Until an alliance is known the declared
 * start is the drawing's own; once one is chosen that differs from {@code DRAWN_FOR}, the declared
 * start becomes the rotated one, and {@link RobotOpMode} moves the pose there. The camera finds the
 * alliance itself: during INIT every camera frame is solved position-only with each known start's
 * own heading ({@code DriveSubsystem.setStartCandidates}, {@link StartPositions#known}), and if
 * one start's solve sits on it for {@link StartMatch#FRAMES_TO_AGREE} frames, the robot is there.
 * One of this Auto's two starts proposes its alliance ({@link #allianceFromStarts}); any other
 * known start is an INIT warning naming it ("On Red audience, not this Auto's start": the wrong
 * Auto was picked, or the robot is on the wrong spot; {@link #cameraOnOtherStart}). One HIVE in
 * view is enough, which is all a start sees. Square (X) or Circle (B) still wins; with no match
 * there is no alliance, and the Auto does not move.
 *
 * <p><b>The drive team may change a few things in INIT</b> ({@link InitOptions}): the PARK spot
 * (D-pad left / right) and, for an Auto drawn with one, when its TIP wait gives up (D-pad up /
 * down, as the partner's TIP time). The generated {@code OPTIONS} says which; the Auto is built at
 * PLAY with the picks, and they go to the match log.
 *
 * <p>While mechanisms are still missing, the names {@link AutoRegistration#PLACEHOLDERS} lists are
 * placeholders (a command that finishes at once, a trigger that never fires), and INIT says so on
 * the Driver Station: the Auto then runs as a timed script, every such wait running to its limit.
 *
 * <p><b>The intake runs for the whole Auto.</b> The Autos are drawn the way the simulator plays
 * them: the roller is on whenever the robot has room for a piece, and a "catch" step is the robot
 * standing in the right place with the roller turning until {@code IntakeFull} or the step's time
 * limit. No card turns the intake on or off, so the drawing and the simulator need none. PLAY
 * starts it ({@link #intakeRequest}); the OpMode's stop idles it. The Auto asks for the intake the
 * whole time; once the lane is full (a piece held under the colour sensor, {@code LaneFull}) the
 * intake holds the last piece in itself ({@code IntakeSubsystem.holdWhenFull}) and {@code IntakeFull}
 * ends the wait, from that one signal. No count of pieces is kept for it.
 *
 * <p>The trace (each card starting, each wait ending and why, the guard's decisions) goes to the
 * match log as events and the last few lines to the Match page. The paths go to the match log too
 * ({@link AutoPathLog}): the declared start as the target during INIT, the whole plan once the
 * Auto is built, at PLAY, since which way round it is drawn depends on the alliance, and the path
 * being driven, and its end, as each one starts and ends.
 *
 * <p><b>A fire waits for an aimed robot.</b> A {@code LaunchAll} right after a path opens the gate
 * on the approach once the robot is aimed and nearly there ({@link LaunchCards#approach()}); failing
 * that, the launch cards feed once the robot is at the last path's end heading and slowing
 * ({@link PathEndSettle}), never on Pedro's "done" alone. Each path end and each settle goes to the
 * match log as an event, with Pedro's own view of how the path ended.
 */
@Configurable
public abstract class BuiltAuto extends RobotOpMode {

    /**
     * The endgame guard (AutoKit.guarded): on, the robot goes for the next volley when its last
     * piece can be out by 30 s, and otherwise parks when the next drive or grab would not leave
     * time to. <b>Off is for practice only</b>: every card runs, so the match log shows
     * how long the whole plan really takes (run it with the Driver Station's 30 s timer off). The
     * Driver Station says so in red while it is off, and the match log records it.
     */
    public static boolean endgameGuard = true;


    /** How many of the Auto's latest trace lines the Match page shows. */
    private static final int TRACE_LINES = 4;

    /** The most pieces a robot may hold (BIOBUZZ G407): the intake has room below this. */
    public static final int MAX_HELD = 4;

    /** The {@code .pp} file in {@code TeamCode/autos/} this Auto was exported from; in the log's metadata. */
    private final String source;
    private final String[] commands;
    private final String[] triggers;
    private final String drawnFor;
    private final Function<Boolean, Pose> startPose;
    private final BiFunction<AutoKit, Boolean, Command> build;
    /** What the drive team may change in INIT, and their picks. */
    private final InitOptions options;
    /** The two places this Auto can start, built once so INIT never allocates. */
    private final StartPosition drawnStart;
    private final StartPosition rotatedStart;

    private AutoRegistry registry;
    /** The placeholder names this Auto uses, for the INIT page. */
    private final List<String> placeholders = new ArrayList<>();
    private long startNs;
    /** Panels' telemetry, or null when Panels could not provide it at init. */
    private TelemetryManager panels;
    private String problem;
    private AutoTrace trace;
    private AutoPathLog pathLog;
    /** Whether the robot has settled after the last path; the launch cards wait for it. */
    private PathEndSettle settle;
    /** The start last written as the log's target, so INIT writes it only when it changes. */
    private StartPosition targetWritten;
    private final StartMatch startMatch = new StartMatch();
    private long startMatchNs;
    /** This Auto's two starts first (drawn, rotated), then every other known start; see the class comment. */
    private final StartPosition[] startCandidates;
    private final Pose[] candidatePoses;
    private final Pose[] candidateFixes;

    protected BuiltAuto(String source, String[] commands, String[] triggers, String drawnFor,
                        Function<Boolean, Pose> startPose, BiFunction<AutoKit, Boolean, Command> build,
                        AutoOption[] options) {
        this.source = source;
        this.commands = commands;
        this.triggers = triggers;
        this.drawnFor = drawnFor;
        this.startPose = startPose;
        this.build = build;
        this.options = new InitOptions(options);
        Alliance drawn = Alliance.valueOf(drawnFor);
        Alliance other = drawn == Alliance.RED ? Alliance.BLUE : Alliance.RED;
        // A drawing that starts on a declared start takes its name and placement sentence.
        StartPosition known = StartPositions.at(startPose.apply(false));
        this.drawnStart = known != null && known.alliance == drawn ? known
                : new StartPosition(drawn + " start (as drawn)", drawn, startPose.apply(false));
        this.rotatedStart = new StartPosition(other + " start (drawing rotated)", other, startPose.apply(true));
        List<StartPosition> candidates = new ArrayList<>();
        candidates.add(drawnStart);
        candidates.add(rotatedStart);
        for (StartPosition start : StartPositions.known()) {
            if (!near(start.pose, drawnStart.pose) && !near(start.pose, rotatedStart.pose)) candidates.add(start);
        }
        startCandidates = candidates.toArray(new StartPosition[0]);
        candidatePoses = new Pose[startCandidates.length];
        for (int i = 0; i < startCandidates.length; i++) candidatePoses[i] = startCandidates[i].pose;
        candidateFixes = new Pose[startCandidates.length];
    }

    private static boolean near(Pose a, Pose b) {
        return Math.hypot(a.x() - b.x(), a.y() - b.y()) <= 1.0;
    }

    /**
     * The drawing's start until an alliance is known; the rotated start once the chosen alliance
     * is not the one the Auto was drawn for. Re-read every INIT loop by {@link RobotOpMode}.
     */
    @Override
    protected StartPosition startPosition() {
        Alliance alliance = setup.alliance();
        boolean rotated = alliance != Alliance.UNKNOWN && !alliance.name().equals(drawnFor);
        return rotated ? rotatedStart : drawnStart;
    }

    @Override
    protected void onInit() {
        panels = panelsTelemetry();
        settle = PathEndSettle.forRobot(robot, line -> log.event(line));
        registry = AutoRegistration.forRobot(robot, setup, settle, line -> log.event(line));
        registry.requireAll(commands, triggers);
        for (String name : AutoRegistration.PLACEHOLDERS) {
            if (Arrays.asList(commands).contains(name) || Arrays.asList(triggers).contains(name)) {
                placeholders.add(name);
            }
        }
        robot.drive.preparePathFollowing();
        robot.drive.setStartCandidates(candidatePoses);
        pathLog = new AutoPathLog(log);
        // Which drawing this was, and which of its waits were running on placeholders.
        log.metadata("AutoSource", source);
        log.metadata("AutoDrawnFor", drawnFor);
        log.metadata("AutoPlaceholders", placeholders.isEmpty() ? "none" : String.join(", ", placeholders));
    }

    @Override
    protected void onInitLoop() {
        // The ghost sits on the robot until the first path moves it; see AutoPathLog.target.
        StartPosition start = startPosition();
        if (start != targetWritten) {
            targetWritten = start;
            pathLog.target(start.pose);
        }
        options.update(gamepad1.dpad_left, gamepad1.dpad_right, gamepad1.dpad_up, gamepad1.dpad_down);
        options.describe(display);
        if (!endgameGuard) {
            display.status("Endgame guard OFF", Display.Level.FAULT,
                    "practice only: no park for time. Panels → BuiltAuto.endgameGuard to turn it back on");
        }
        if (!placeholders.isEmpty()) {
            display.status("Placeholders", Display.Level.WARN, String.join(", ", placeholders)
                    + ": no mechanism yet, so these waits run to their limits");
        }
    }

    /** For whoever wrote the Auto, not the drive team: off the one-screen INIT page. */
    @Override
    protected void describeRobotPage(Display display) {
        display.section("Auto");
        display.line(source + ": drawn for " + drawnFor + "; the other alliance runs it rotated.");
    }

    /** Which known start the camera puts the robot on, each tried with its own heading; see the class comment. */
    @Override
    protected Alliance allianceFromStarts() {
        long ns = robot.drive.candidateFixNs();
        if (ns != 0 && ns != startMatchNs) {
            startMatchNs = ns;
            for (int i = 0; i < candidateFixes.length; i++) candidateFixes[i] = robot.drive.candidateFix(i);
            int before = startMatch.settled();
            int now = startMatch.update(candidateFixes, startCandidates);
            if (now != before) {
                log.event(now == StartMatch.NONE ? "Start: the camera no longer puts the robot on a known start"
                        : now < 2 ? "Start: the camera puts the robot on the " + startCandidates[now].alliance + " start"
                        : "Start: the camera puts the robot on " + startCandidates[now].name + ", not this Auto's start");
            }
        }
        int on = startMatch.settled();
        return on == 0 || on == 1 ? startCandidates[on].alliance : Alliance.UNKNOWN;
    }

    /** The known start the camera puts the robot on when it is not one of this Auto's, else null. */
    @Override
    protected StartPosition cameraOnOtherStart() {
        int on = startMatch.settled();
        return on >= 2 ? startCandidates[on] : null;
    }

    /** This Auto's start for {@code alliance}: as drawn, or rotated. */
    @Override
    protected StartPosition startFor(Alliance alliance) {
        return alliance == drawnStart.alliance ? drawnStart : rotatedStart;
    }

    @Override
    protected void onStart() {
        robot.drive.setStartCandidates();
        options.lock();
        if (!options.isEmpty()) log.metadata("AutoOptions", options.summary());
        Alliance alliance = setup.alliance();
        if (alliance == Alliance.UNKNOWN) {
            problem = "No alliance chosen before PLAY (Square (X) = blue, Circle (B) = red during INIT). Not moving.";
            return;
        }
        // The CELLs start the match where the manual puts them (each alliance's LEFT DOWN, RIGHT
        // UP): Tip, LeftCellUp and RightCellUp read from there until the camera sees the HIVE
        // settle (AutoRegistration). Position fixes still use only what the camera settled.
        robot.vision.seedMatchStart();
        robot.hive.assumeMatchStart();
        boolean rotated = !alliance.name().equals(drawnFor);
        robot.drive.setPose(startPose.apply(rotated));
        startNs = System.nanoTime();
        // Every line to the match log, the last few to the Match page.
        trace = new AutoTrace(TRACE_LINES, line -> log.event(line));
        AutoKit kit = new AutoKit(autoDrive(rotated), registry, () -> (System.nanoTime() - startNs) / 1e9)
                .trace(trace)
                .watchPaths(both(pathLog, settle))
                .picks(options)
                .guard(endgameGuard);
        if (!endgameGuard) log.event("Endgame guard OFF (practice): every card runs, no park for time");
        Command auto = build.apply(kit, rotated);
        pathLog.plan(kit.paths());
        auto.schedule();
        // Asked for the whole Auto: the intake stops its roller itself when the lane is full.
        if (intakeRequest(0) == IntakeSubsystem.State.IN) robot.intake.intake();
    }

    /** Trial-specific path constraints; ordinary Autos use the drivetrain directly. */
    protected AutoDrive autoDrive(boolean rotated) { return robot.drive; }

    /**
     * What the Auto asks of the intake while it runs: in while the robot has room, idle once it
     * holds {@link #MAX_HELD}. The one place the "intake on whenever there is room" rule is written.
     */
    static IntakeSubsystem.State intakeRequest(int held) {
        return held < MAX_HELD ? IntakeSubsystem.State.IN : IntakeSubsystem.State.IDLE;
    }

    @Override
    protected void onLoop() {
        if (problem != null) {
            display.status("Auto", Display.Level.FAULT, problem);
            return;
        }
        settle.update();
        if (!endgameGuard) {
            display.status("Endgame guard OFF", Display.Level.FAULT,
                    "practice only: no park for time. Panels → BuiltAuto.endgameGuard to turn it back on");
        }
        if (trace != null) trace.forEachRecent(display::line);
        publish();
    }

    /**
     * The launch path's numbers to Panels, under the same keys as Basic Drive and Bench: Launch Test, so the
     * same graphs work in an Auto. Flat keys, one update per loop; never takes the robot down.
     */
    private void publish() {
        if (panels == null) return;
        try {
            panels.addData("left_target_tps", robot.launcher.isSpinning() ? robot.launcher.leftTarget() : 0.0);
            panels.addData("right_target_tps", robot.launcher.isSpinning() ? robot.launcher.rightTarget() : 0.0);
            panels.addData("left_tps", robot.launcher.leftTicksPerSecond());
            panels.addData("right_tps", robot.launcher.rightTicksPerSecond());
            panels.addData("at_speed", robot.launcher.atSpeed() ? 1.0 : 0.0);
            panels.addData("shots", robot.launcher.shots());
            panels.addData("feeder_power", robot.feeder.power());
            panels.addData("feeder_tps", robot.feeder.ticksPerSecond());
            panels.addData("gate_feeding", robot.feedGate.state() == FeedGateSubsystem.State.FEEDING ? 1.0 : 0.0);
            LanePanels.publish(panels, robot.colorSensor.lane());
            panels.addData("battery_volts", batteryVolts());
            panels.addData("loop_ms", loopTimer.lastMs());
            panels.update();
        } catch (RuntimeException ignored) {
            // Telemetry never takes a mechanism down.
        }
    }

    /** AutoKit takes one path watcher; the log and the settle check both need every start and end. */
    private static AutoKit.PathWatcher both(AutoKit.PathWatcher first, AutoKit.PathWatcher second) {
        return new AutoKit.PathWatcher() {
            @Override public void pathStarted(Path path) {
                first.pathStarted(path);
                second.pathStarted(path);
            }

            @Override public void pathEnded(Path path) {
                first.pathEnded(path);
                second.pathEnded(path);
            }
        };
    }
}
